import assert from 'node:assert/strict';
import fs from 'node:fs';
import { importMetronomo } from '../scripts/importers/metronomoComposto.js';
import { createState, applyRhythmChart, addNoteEvent, addRestEvent, undoLastEvent, getCursorPosition } from '../scripts/state.js';
import { timedBars, slotToSeconds, secondsToSlot, chartEnd } from '../scripts/timeline.js';
const fixture = JSON.parse(fs.readFileSync(new URL('./fixtures/metronomo-test.json',import.meta.url)));
const chart = importMetronomo(fixture);
assert.deepEqual(chart.bars.map(b=>b.lengthSlots),[10,7,2]);
assert.deepEqual(chart.bars.map(b=>b.startSlot),[0,10,17]);
const state = createState(); applyRhythmChart(state,chart);
const times = timedBars(state);
assert.equal(times.at(-1).endSeconds,4.75);
assert.equal(slotToSeconds(times,10),2.5);
assert.equal(secondsToSlot(times,2.5),10);
assert.equal(secondsToSlot(times,4.75),null);
assert.equal(chartEnd(state),19);
state.cursorSlot = 10;
assert.equal(getCursorPosition(state).bar,2);
state.cursorSlot = 9; state.selectedDurationSlots = 2;
assert.throws(()=>addRestEvent(state),/crosses/);
assert.equal(state.events.length,0);
state.selectedDurationSlots = 1;
addNoteEvent(state,{string:6,fret:3,midi:43,noteName:'G2'});
assert.equal(state.cursorSlot,10);
undoLastEvent(state); assert.equal(state.cursorSlot,9);
state.cursorSlot=19; assert.throws(()=>addRestEvent(state),/End/);
const denom = structuredClone(fixture); denom.unit='denom';
applyRhythmChart(state,importMetronomo(denom));
assert.equal(timedBars(state).at(-1).endSeconds,7);
const repeat=structuredClone(fixture); repeat.bars[0].rep=2;
assert.equal(importMetronomo(repeat).bars.length,4);
const variable=structuredClone(fixture); variable.perBar=true; variable.bars[1].bpm=60;
applyRhythmChart(state,importMetronomo(variable));
assert.equal(timedBars(state).at(-1).endSeconds,6.5);
const unsupported=structuredClone(fixture); unsupported.bars[0].den=16;
assert.throws(()=>importMetronomo(unsupported),/denominators/);
const invalid=structuredClone(fixture); invalid.bars[0].acc[0]=9;
assert.throws(()=>importMetronomo(invalid),/accent/);
assert.throws(()=>importMetronomo({...fixture,version:99}),/version/);
const free=createState(); free.events=[{startSlot:0,durationSlots:2}];
assert.equal(chartEnd(free),8);
console.log('PASS: sample import, positions, timing, denominator tempo, per-bar tempo, repeats, boundaries, validation and free 4/4.');
